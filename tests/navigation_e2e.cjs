// Real-browser UI regression with synthetic API responses; never contacts WhatsApp or an LLM.
// Run in a Linux Playwright environment: node tests/navigation_e2e.cjs
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const http = require('node:http');
const path = require('node:path');
const artifacts = process.env.CARBON_UI_ARTIFACT_DIR || '/tmp/carbon-navigation-e2e';
fs.mkdirSync(artifacts,{recursive:true});
const requests=[];
let pairingOpen=false;
let relinkRequired=false;
const admin='00000000-0000-4000-8000-000000000001';
const server=http.createServer((req,res)=>{
  let body='';req.on('data',data=>body+=data);req.on('end',()=>{
    const url=req.url.split('?')[0];requests.push({url,body});
    res.setHeader('Cache-Control','no-store');
    let data;
    if(url==='/api/status') data={whatsapp:relinkRequired?'Logged out':'Not linked',relink_required:relinkRequired,model:'test/model',true_admins:[admin],has_qr:pairingOpen&&!relinkRequired,qr_version:'test-qr',qr_expires_in:60};
    if(url==='/api/whatsapp/unlink'){relinkRequired=false;data={};}
    if(url==='/api/whatsapp/pairing-view'){pairingOpen=JSON.parse(body).open;res.writeHead(204);res.end();return;}
    if(url==='/api/models') data={models:['test/model','test/alternate']};
    if(url==='/api/participants') data=[{id:admin,label:'+15550000001 (synthetic@lid)',identity:'synthetic@lid'}];
    if(url==='/api/approval-requests') data={requests:[{summary:'Create group Test community?',state:'pending',identity_label:'+15550000001',expires:2000000000}]};
    if(url==='/api/activity') data={events:[{id:1,created:1900000000,event:'app_started',message:'Carbon started',level:'info',operation_id:null}]};
    if(data!==undefined){res.setHeader('Content-Type','application/json');res.end(JSON.stringify(data));return;}
    if(url==='/api/whatsapp/qr.svg'){res.setHeader('Content-Type','image/svg+xml');res.end('<svg xmlns="http://www.w3.org/2000/svg" width="280" height="280"><rect width="280" height="280" fill="white"/><path d="M20 20h80v80H20zM180 20h80v80h-80zM20 180h80v80H20z"/></svg>');return;}
    const files={'/':'web/index.html','/app.js':'web/app.js','/app.css':'web/app.css','/logo.png':'web/logo.png'};
    if(files[url]){res.setHeader('Content-Type',url.endsWith('.css')?'text/css':url.endsWith('.js')?'text/javascript':url.endsWith('.png')?'image/png':'text/html');res.end(fs.readFileSync(files[url]));return;}
    res.writeHead(404);res.end();
  });
});
(async()=>{
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const browser=await chromium.launch({headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1280,height:900}});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    let nativeDialogs=0;
    page.on('dialog',async dialog=>{nativeDialogs++;await dialog.dismiss();});
    const base='http://127.0.0.1:'+server.address().port;
    await page.goto(base);
    await page.waitForFunction(()=>document.querySelector('#connection').textContent==='Not linked');
    assert.equal(await page.locator('#whatsapp-panel').getAttribute('open'),null);
    assert.ok(!requests.some(r=>r.url==='/api/whatsapp/pairing-view' && JSON.parse(r.body).open));
    assert.ok(!requests.some(r=>r.url==='/api/models'));
    assert.equal(await page.locator('[data-page="channels"]').getAttribute('aria-current'),'page');
    const contrast=await page.evaluate(()=>{
      const rgb=color=>color.match(/[\d.]+/g).slice(0,3).map(Number).map(v=>v/255);
      const lum=color=>rgb(color).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4).reduce((sum,v,i)=>sum+v*[.2126,.7152,.0722][i],0);
      const ratio=(a,b)=>{const values=[lum(a),lum(b)].sort((x,y)=>x-y);return (values[1]+.05)/(values[0]+.05);};
      const base=getComputedStyle(document.documentElement);
      const nav=getComputedStyle(document.querySelector('[aria-current="page"]'));
      return {body:ratio(base.color,base.backgroundColor),navigation:ratio(nav.color,nav.backgroundColor)};
    });
    assert.ok(contrast.body>=4.5 && contrast.navigation>=4.5, 'Body and selected navigation text need readable contrast');
    await page.screenshot({path:path.join(artifacts,'desktop-expanded.png')});
    assert.equal(await page.locator('#app-navigation #nav-toggle').count(),1);
    const toggleBox=await page.locator('#nav-toggle').boundingBox();
    const sidebarBox=await page.locator('#app-navigation').boundingBox();
    assert.ok(toggleBox.x>=sidebarBox.x && toggleBox.x+toggleBox.width<=sidebarBox.x+sidebarBox.width, 'Footer toggle must stay inside sidebar');
    assert.ok(Math.abs(sidebarBox.y+sidebarBox.height-toggleBox.y-toggleBox.height-16)<2, 'Toggle must sit at sidebar bottom');
    assert.ok(await page.evaluate(({x,y})=>Boolean(document.elementFromPoint(x,y)?.closest('#nav-toggle')), {x:toggleBox.x+toggleBox.width/2,y:toggleBox.y+4}), 'Footer toggle must remain clickable');
    const lastLinkBox=await page.locator('[data-page="activity"]').boundingBox();
    assert.ok(toggleBox.y>=lastLinkBox.y+lastLinkBox.height+12, 'Footer toggle must be separated from menu items');
    const expandedLeft=await page.locator('#main-content').evaluate(el=>el.getBoundingClientRect().left);
    await page.locator('#nav-toggle').click();
    await page.waitForFunction(()=>document.body.classList.contains('nav-collapsed'));
    assert.equal(await page.locator('#nav-toggle').getAttribute('aria-expanded'),'false');
    await page.waitForTimeout(250);
    const collapsedLeft=await page.locator('#main-content').evaluate(el=>el.getBoundingClientRect().left);
    assert.ok(collapsedLeft<expandedLeft);
    await page.screenshot({path:path.join(artifacts,'desktop-collapsed.png')});
    await page.reload();assert.equal(await page.locator('#nav-toggle').getAttribute('aria-expanded'),'false');
    await page.locator('#whatsapp-panel summary').click();
    await page.waitForFunction(()=>!document.querySelector('#qr').hidden);
    assert.ok(requests.some(r=>r.url==='/api/whatsapp/pairing-view' && JSON.parse(r.body).open));
    const pairingReleased=page.waitForResponse(r=>r.url().endsWith('/api/whatsapp/pairing-view') && JSON.parse(r.request().postData()).open===false);
    await page.locator('[data-page="model"]').click();
    await pairingReleased;
    await page.waitForFunction(()=>document.querySelector('#model').options.length===2);
    await page.waitForFunction(()=>document.querySelector('#whatsapp-panel').open===false);
    await page.waitForFunction(()=>document.querySelector('#qr').hidden);
    assert.equal(pairingOpen,false);
    await page.locator('[data-page="admin"]').click();
    await page.waitForFunction(()=>document.querySelector('#approvals-list').children.length===1);
    assert.equal(await page.locator('#review-panel').isVisible(),true);
    assert.equal(await page.locator('#approvals-panel').isVisible(),true);
    await page.locator('#skip-content').focus();
    await page.locator('#skip-content').click();
    assert.equal(await page.locator('#admin-page').isVisible(),true);
    assert.equal(await page.locator('#main-content').evaluate(el=>el===document.activeElement),true);
    const adminHeading=await page.locator('#admin-title').boundingBox();
    const appHeader=await page.locator('.app-header').boundingBox();
    assert.ok(adminHeading.y>=appHeader.y+appHeader.height, 'Skip-to-content must leave the page heading visible');
    await page.locator('#nav-toggle').click();
    await page.waitForTimeout(250);
    await page.screenshot({path:path.join(artifacts,'desktop-admin.png')});
    await page.goBack();assert.equal(await page.locator('#model-page').isVisible(),true);
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>document.querySelector('#app-navigation').inert);
    assert.equal(await page.locator('#nav-backdrop').isVisible(),false);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.locator('#mobile-nav-toggle').click();
    assert.equal(await page.locator('#main-content').evaluate(el=>el.inert),true);
    assert.equal(await page.locator('#mobile-nav-toggle').getAttribute('aria-expanded'),'true');
    await page.waitForTimeout(250);
    await page.screenshot({path:path.join(artifacts,'mobile-open.png')});
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#mobile-nav-toggle').evaluate(el=>el===document.activeElement),true);
    assert.equal(await page.locator('#main-content').evaluate(el=>el.inert),false);
    await page.locator('#mobile-nav-toggle').click();
    await page.locator('[data-page="channels"]').click();
    assert.equal(await page.locator('#nav-backdrop').isVisible(),false);
    assert.equal(await page.locator('#whatsapp-panel').getAttribute('open'),null);
    await page.waitForTimeout(250);
    await page.screenshot({path:path.join(artifacts,'mobile-closed.png')});
    await page.locator('#mobile-nav-toggle').click();
    await page.locator('[data-page="activity"]').click();
    await page.waitForFunction(()=>document.querySelector('#activity-list').children.length===1);
    relinkRequired=true;
    await page.locator('#mobile-nav-toggle').click();
    await page.locator('[data-page="channels"]').click();
    await page.waitForFunction(()=>document.querySelector('#app-navigation').getBoundingClientRect().right<=0);
    await page.locator('#whatsapp-panel summary').click();
    await page.waitForFunction(()=>document.querySelector('#unlink-whatsapp').textContent==='Relink WhatsApp');
    assert.equal(await page.locator('#unlink-whatsapp').isVisible(),true);
    assert.equal(await page.locator('#qr-loading').isVisible(),false);
    assert.equal(await page.locator('#qr').isVisible(),false);
    assert.equal(await page.locator('#relink-help').isVisible(),true);
    assert.equal(await page.locator('#pairing-help').isVisible(),false);
    await page.screenshot({path:path.join(artifacts,'mobile-relink-required.png')});
    await page.locator('#unlink-whatsapp').click();
    const confirmation=page.getByRole('dialog',{name:'Relink WhatsApp?'});
    assert.equal(await confirmation.isVisible(),true);
    assert.equal(await confirmation.getByRole('button',{name:'Cancel'}).evaluate(el=>el===document.activeElement),true);
    await page.keyboard.press('Escape');
    assert.equal(await confirmation.isVisible(),false);
    assert.equal(requests.filter(r=>r.url==='/api/whatsapp/unlink').length,0);
    assert.equal(await page.locator('#unlink-whatsapp').evaluate(el=>el===document.activeElement),true);
    await page.locator('#unlink-whatsapp').click();
    await confirmation.getByRole('button',{name:'Cancel'}).click();
    assert.equal(requests.filter(r=>r.url==='/api/whatsapp/unlink').length,0);
    await page.locator('#unlink-whatsapp').click();
    const box=await confirmation.boundingBox();
    assert.ok(box.x>=0 && box.x+box.width<=390 && box.y>=0 && box.y+box.height<=844);
    await page.screenshot({path:path.join(artifacts,'mobile-relink-modal.png')});
    await page.setViewportSize({width:1280,height:900});
    await page.screenshot({path:path.join(artifacts,'desktop-relink-modal.png')});
    await confirmation.getByRole('button',{name:'Relink WhatsApp',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('#qr').hidden);
    assert.equal(requests.filter(r=>r.url==='/api/whatsapp/unlink').length,1);
    assert.equal(nativeDialogs,0);
    assert.deepEqual(errors,[]);
    console.log('Navigation E2E passed: rail persistence, responsive drawer, Escape/focus, combined Admin, history, no overflow and on-demand QR lifecycle.');
  } finally {await browser.close();server.close();}
})().catch(error=>{console.error(error);server.close();process.exitCode=1;});
